"use client";

import { useState } from "react";
import Link from "next/link";

type GenResult = {
  title?: string;
  description?: string;
  modules?: { title: string; lessons: { title: string; contentSummary: string }[] }[];
  questions?: { text: string; options: string[]; correctAnswer: string; explanation: string }[];
  cards?: { front: string; back: string }[];
  raw?: string;
};

export default function AIAuthoringPage() {
  const [inputText, setInputText] = useState("");
  const [genType, setGenType] = useState<"course_outline" | "quiz" | "flashcards">("course_outline");
  const [result, setResult] = useState<GenResult | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const [provider, setProvider] = useState("");

  async function generate() {
    if (!inputText.trim()) return;
    setLoading(true);
    setError("");
    setResult(null);

    try {
      const res = await fetch("/api/ai-generate", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ type: genType, inputText }),
      });
      const data = await res.json();
      if (!res.ok) {
        setError(data.error || "Generation failed");
      } else {
        setResult(data.result);
        setProvider(data.provider || "unknown");
      }
    } catch {
      setError("Network error");
    }
    setLoading(false);
  }

  return (
    <div className="mx-auto max-w-5xl px-4 py-8">
      <Link href="/admin" className="mb-4 inline-block text-sm text-indigo-600 hover:underline">← Admin Dashboard</Link>
      <h1 className="text-2xl font-bold text-slate-800 dark:text-slate-100">🤖 AI Course Authoring</h1>
      <p className="mt-1 text-slate-500 dark:text-slate-400">
        Paste your raw notes, documentation, or any text. AI will generate structured content for you.
      </p>

      <div className="mt-6 grid gap-6 md:grid-cols-2">
        {/* Input side */}
        <div>
          <label className="mb-2 block text-sm font-semibold text-slate-700 dark:text-slate-300">Generation Type</label>
          <div className="mb-3 flex gap-2">
            {(["course_outline", "quiz", "flashcards"] as const).map((t) => (
              <button
                key={t}
                onClick={() => setGenType(t)}
                className={`rounded-lg px-3 py-1.5 text-sm font-medium ${
                  genType === t
                    ? "bg-indigo-600 text-white"
                    : "bg-slate-100 text-slate-600 hover:bg-slate-200 dark:bg-slate-800 dark:text-slate-300"
                }`}
              >
                {t === "course_outline" ? "📚 Outline" : t === "quiz" ? "❓ Quiz" : "🎴 Flashcards"}
              </button>
            ))}
          </div>

          <textarea
            value={inputText}
            onChange={(e) => setInputText(e.target.value)}
            placeholder="Paste your raw content here — lecture notes, textbook chapters, technical documentation, etc."
            className="h-64 w-full rounded-xl border border-slate-300 p-4 text-sm dark:bg-slate-900 dark:border-slate-600 dark:text-slate-100"
          />

          <button
            onClick={generate}
            disabled={loading || !inputText.trim()}
            className="mt-3 w-full rounded-xl bg-gradient-to-r from-indigo-600 to-purple-600 px-5 py-3 text-sm font-bold text-white hover:from-indigo-700 hover:to-purple-700 disabled:opacity-50"
          >
            {loading ? "🤖 Generating..." : "✨ Generate with AI"}
          </button>
          {provider && result && (
            <p className="mt-2 text-xs text-slate-400">Generated by: {provider}</p>
          )}
        </div>

        {/* Output side */}
        <div>
          <label className="mb-2 block text-sm font-semibold text-slate-700 dark:text-slate-300">AI Output</label>
          {error ? (
            <div className="rounded-xl border border-red-300 bg-red-50 p-4 text-sm text-red-700">
              <p className="font-semibold">⚠️ {error}</p>
              {error.includes("API key") && (
                <p className="mt-2 text-xs">
                  Go to Render.com → your service → Environment → add <code>GROQ_API_KEY</code> (free at groq.com).
                </p>
              )}
            </div>
          ) : !result ? (
            <div className="flex h-64 items-center justify-center rounded-xl border-2 border-dashed border-slate-300 text-sm text-slate-400">
              Results will appear here
            </div>
          ) : (
            <div className="max-h-96 overflow-y-auto rounded-xl border border-slate-200 bg-slate-50 p-4 dark:border-slate-700 dark:bg-slate-800">
              {result.title && <h2 className="text-lg font-bold text-slate-800 dark:text-slate-100">{result.title}</h2>}
              {result.description && <p className="mt-1 text-sm text-slate-600 dark:text-slate-300">{result.description}</p>}

              {result.modules?.map((m, i) => (
                <div key={i} className="mt-3 border-l-2 border-indigo-400 pl-3">
                  <h3 className="font-semibold text-sm">Module {i + 1}: {m.title}</h3>
                  {m.lessons?.map((l, j) => (
                    <div key={j} className="mt-1 text-xs text-slate-500">
                      • {l.title} — <em>{l.contentSummary}</em>
                    </div>
                  ))}
                </div>
              ))}

              {result.questions?.map((q, i) => (
                <div key={i} className="mt-3 rounded-lg bg-white p-3 dark:bg-slate-900">
                  <p className="text-sm font-medium">{i + 1}. {q.text}</p>
                  <ul className="mt-1 text-xs text-slate-500">
                    {q.options?.map((o, j) => (
                      <li key={j} className={o === q.correctAnswer ? "font-bold text-green-600" : ""}>
                        {String.fromCharCode(65 + j)}. {o} {o === q.correctAnswer ? "✓" : ""}
                      </li>
                    ))}
                  </ul>
                  <p className="mt-1 text-xs italic text-slate-400">💡 {q.explanation}</p>
                </div>
              ))}

              {result.cards?.map((c, i) => (
                <div key={i} className="mt-2 rounded-lg bg-white p-3 dark:bg-slate-900">
                  <p className="text-sm font-semibold">{c.front}</p>
                  <p className="text-xs text-slate-500">{c.back}</p>
                </div>
              ))}

              {result.raw && (
                <pre className="whitespace-pre-wrap text-xs text-slate-600 dark:text-slate-300">{result.raw}</pre>
              )}
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
